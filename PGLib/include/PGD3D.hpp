#pragma once

#include <DirectXTex.h>

#include <array>
#include <chrono>
#include <cstddef>
#include <d3d11.h>
#include <d3dcommon.h>
#include <dxgiformat.h>
#include <filesystem>
#include <minwindef.h>
#include <mutex>
#include <shared_mutex>
#include <span>
#include <string>
#include <unordered_map>
#include <vector>
#include <winnt.h>
#include <wrl/client.h>

/**
 * @brief Direct3D 11 compute helpers for reading and converting DDS textures on the GPU.
 *
 * initGPU() and initShaders() must succeed before any GPU function is used; the GPU functions throw std::runtime_error
 * otherwise. Every device and context call is serialized by one mutex, so the object can be shared between threads.
 */
class PGD3D {
public:
    /// @brief Compiled shader bytecode, as the headers generated by cmake/PGShaders.cmake hold it
    using ShaderBytecode = std::span<const unsigned char>;

    /// @brief How long getDDSMetadata() remembers a failed read unless setDDSMetadataRetryInterval() says otherwise.
    static constexpr std::chrono::seconds defaultDDSMetadataRetryInterval { 5 };

private:
    std::mutex m_d3dMutex;

    static constexpr unsigned numGPUThreads = 16;
    static constexpr unsigned gpuBufferSizeMultiple = 16;
    static constexpr unsigned maxChannelValue = 255;

    // GPU objects.
    Microsoft::WRL::ComPtr<ID3D11Device> m_ptrDevice; // GPU device
    Microsoft::WRL::ComPtr<ID3D11DeviceContext> m_ptrContext; // GPU context

    static inline const D3D_FEATURE_LEVEL s_featureLevel = D3D_FEATURE_LEVEL_11_0; // DX11

    std::unordered_map<std::filesystem::path, DirectX::TexMetadata> m_ddsMetaDataCache;
    std::shared_mutex m_ddsMetaDataMutex;

    /// @brief A metadata read that failed: when, and whether the file could not be read this time (as opposed to not
    /// being a DDS file), see getDDSMetadata(). Guarded by m_ddsMetaDataMutex.
    struct DDSMetadataFailure {
        std::chrono::steady_clock::time_point time;
        bool isReadFailure = false;
    };
    std::unordered_map<std::filesystem::path, DDSMetadataFailure> m_ddsMetaDataFailures;
    std::chrono::steady_clock::duration m_ddsMetadataRetryInterval = defaultDDSMetadataRetryInterval;

    // Global shader storage.
    Microsoft::WRL::ComPtr<ID3D11ComputeShader> m_shaderCountAlphaValues;

public:
    //
    // Static Helpers.
    //

    /**
     * @brief Get the error message from a HRESULT
     *
     * @param hr HRESULT
     * @return std::wstring error message
     */
    static std::wstring hresultErrorMessage(HRESULT hr);

    /**
     * @brief Get the DXGI_FORMAT for an output format name used in patcher options
     *
     * @param format "rgba16f" or "rgba32f"
     * @return DXGI_FORMAT_R16G16B16A16_FLOAT, DXGI_FORMAT_R32G32B32A32_FLOAT, or DXGI_FORMAT_UNKNOWN for any other
     * string
     */
    static DXGI_FORMAT dxgiFormatFromString(const std::string& format);

    //
    // Instance Functions.
    //

    /**
     * @brief Construct a new PGD3D object. Nothing touches the GPU until initGPU().
     */
    PGD3D() = default;

    /**
     * @brief Create the D3D11 device and context on the default hardware adapter. This must be called before any
     * other GPU function
     *
     * @return true on success
     * @return false on failure
     */
    bool initGPU();

    /**
     * @brief Create the shaders PGD3D uses itself (CountAlphaValues.hlsl) on the GPU
     *
     * @return true on success
     * @return false on failure
     * @throws std::runtime_error if the GPU was not initialized
     */
    bool initShaders();

    //
    // Global Runners (they use helpers below).
    //

    /**
     * @brief Run a compute shader over a texture and read the result back with a full mip chain
     *
     * The shader is dispatched once per input pixel (16x16 thread groups) with the input texture in t0 and the output
     * texture in u0.
     *
     * @param inTexture input texture, its dimensions must be powers of two
     * @param[out] outTexture output texture
     * @param shader compiled shader to run
     * @param outFormat format of the output texture
     * @param outWidth width of the output texture, 0 for the input width
     * @param outHeight height of the output texture, 0 for the input height
     * @param shaderParams constant buffer contents for b0, or nullptr for none
     * @param shaderParamsSize size of shaderParams in bytes
     * @return true on success
     * @return false on failure
     * @throws std::runtime_error if shader is null or the GPU was not initialized
     */
    bool applyShaderToTexture(const DirectX::ScratchImage& inTexture,
                              DirectX::ScratchImage& outTexture,
                              const Microsoft::WRL::ComPtr<ID3D11ComputeShader>& shader,
                              const DXGI_FORMAT& outFormat = DXGI_FORMAT_R8G8B8A8_UNORM,
                              const UINT& outWidth = 0,
                              const UINT& outHeight = 0,
                              const void* shaderParams = nullptr,
                              const UINT& shaderParamsSize = 0);

    /**
     * @brief Classify an environment mask texture as a complex material texture
     *
     * A texture whose format has no alpha channel, or whose alpha is 255 for more than half of the pixels, is not a
     * complex material texture. Otherwise the red, green and blue channels say which complex material features it
     * carries. The out parameters are only ever set to true, so the caller initializes them.
     *
     * @param ddsPath lower case path of the texture relative to the data folder
     * @param[out] result true if the texture is a complex material texture
     * @param[out] hasEnvMask set when the red channel is used
     * @param[out] hasGlosiness set when the green channel is used
     * @param[out] hasMetalness set when the blue channel is used
     * @return true if the texture could be read and classified, false otherwise (result is false then)
     */
    bool checkIfCM(const std::filesystem::path& ddsPath,
                   bool& result,
                   bool& hasEnvMask,
                   bool& hasGlosiness,
                   bool& hasMetalness);

    /**
     * @brief Count, per channel, the pixels of the first mip level that carry a value (see CountAlphaValues.hlsl)
     *
     * @param image input image
     * @param[out] outData number of pixels with red, green, blue >= 4/255 and the number of pixels with alpha 255
     * @return true on success
     * @return false on failure
     * @throws std::runtime_error if the GPU or its shaders were not initialized
     */
    bool countPixelValues(const DirectX::ScratchImage& image,
                          std::array<int,
                                     4>& outData);

    //
    // GPU Helpers.
    //

    /**
     * @brief Create a compute shader on the GPU from its compiled bytecode (the shaders are compiled at build time, see
     * cmake/PGShaders.cmake)
     *
     * @param bytecode Compiled bytecode of the shader
     * @param[out] outShader Output shader
     * @return true on success
     * @return false on failure or empty bytecode
     * @throws std::runtime_error if the GPU was not initialized
     */
    bool initShader(ShaderBytecode bytecode,
                    Microsoft::WRL::ComPtr<ID3D11ComputeShader>& outShader);

    /**
     * @brief Create a Texture2D object on the GPU from a ScratchImage
     *
     * @param texture ScratchImage to create texture from, its dimensions must be powers of two
     * @param[out] dest Output texture
     * @return true on success
     * @return false on failure
     */
    bool createTexture2D(const DirectX::ScratchImage& texture,
                         Microsoft::WRL::ComPtr<ID3D11Texture2D>& dest);

    /**
     * @brief Create an empty Texture2D object with the description of an existing Texture2D
     *
     * @param existingTexture Existing texture, its dimensions must be even
     * @param[out] dest Output texture
     * @return true on success
     * @return false on failure
     */
    bool createTexture2D(Microsoft::WRL::ComPtr<ID3D11Texture2D>& existingTexture,
                         Microsoft::WRL::ComPtr<ID3D11Texture2D>& dest);

    /**
     * @brief Create a Texture2D object from a description
     *
     * @param desc Texture description
     * @param[out] dest Output texture
     * @return true on success
     * @return false on failure
     */
    bool createTexture2D(D3D11_TEXTURE2D_DESC& desc,
                         Microsoft::WRL::ComPtr<ID3D11Texture2D>& dest);

    /**
     * @brief Create a Shader Resource View for a Texture2D
     *
     * @param texture Texture2D object
     * @param[out] dest Output Shader Resource View
     * @return true on success
     * @return false on failure
     */
    bool createShaderResourceView(const Microsoft::WRL::ComPtr<ID3D11Texture2D>& texture,
                                  Microsoft::WRL::ComPtr<ID3D11ShaderResourceView>& dest);

    /**
     * @brief Create a Unordered Access View object from a Texture2D
     *
     * @param texture Texture2D object
     * @param[out] dest Output Unordered Access View
     * @return true on success
     * @return false on failure
     */
    bool createUnorderedAccessView(const Microsoft::WRL::ComPtr<ID3D11Texture2D>& texture,
                                   Microsoft::WRL::ComPtr<ID3D11UnorderedAccessView>& dest);

    /**
     * @brief Create a Unordered Access View object from a generic resource and description
     *
     * @param gpuResource generic resource
     * @param desc description
     * @param[out] dest Output Unordered Access View
     * @return true on success
     * @return false on failure
     */
    bool createUnorderedAccessView(const Microsoft::WRL::ComPtr<ID3D11Resource>& gpuResource,
                                   const D3D11_UNORDERED_ACCESS_VIEW_DESC& desc,
                                   Microsoft::WRL::ComPtr<ID3D11UnorderedAccessView>& dest);

    /**
     * @brief Create a Buffer object
     *
     * @param data buffer data
     * @param desc buffer description
     * @param[out] dest Output buffer
     * @return true on success
     * @return false on failure
     */
    bool createBuffer(const void* data,
                      D3D11_BUFFER_DESC& desc,
                      Microsoft::WRL::ComPtr<ID3D11Buffer>& dest);

    /**
     * @brief Create a Constant Buffer object
     *
     * @param data constant buffer data
     * @param size size of the buffer
     * @param[out] dest Output constant buffer
     * @return true on success
     * @return false on failure
     */
    bool createConstantBuffer(const void* data,
                              const UINT& size,
                              Microsoft::WRL::ComPtr<ID3D11Buffer>& dest);

    /**
     * @brief Dispatch a compute shader and block until it finished
     *
     * @param shader shader to dispatch
     * @param srvs shader resource views, bound to t0, t1, ...
     * @param uavs unordered access views, bound to u0, u1, ...
     * @param constantBuffers constant buffers, bound to b0, b1, ...
     * @param threadGroupCountX number of threads in X, dispatched in groups of 16
     * @param threadGroupCountY number of threads in Y, dispatched in groups of 16
     * @param threadGroupCountZ number of threads in Z, dispatched in groups of 16
     * @return true on success
     * @return false on failure
     */
    [[nodiscard]] bool blockingDispatch(const Microsoft::WRL::ComPtr<ID3D11ComputeShader>& shader,
                                        const std::vector<Microsoft::WRL::ComPtr<ID3D11ShaderResourceView>>& srvs,
                                        const std::vector<Microsoft::WRL::ComPtr<ID3D11UnorderedAccessView>>& uavs,
                                        const std::vector<Microsoft::WRL::ComPtr<ID3D11Buffer>>& constantBuffers,
                                        UINT threadGroupCountX,
                                        UINT threadGroupCountY,
                                        UINT threadGroupCountZ);

    /**
     * @brief read back a texture from the GPU
     *
     * @param gpuResource texture to read back
     * @param[out] outImage output image
     * @return true on success
     * @return false on failure
     */
    [[nodiscard]] bool readBack(const Microsoft::WRL::ComPtr<ID3D11Texture2D>& gpuResource,
                                DirectX::ScratchImage& outImage);

    /**
     * @brief Read back a buffer from the GPU. Only defined in PGD3D.cpp, for the element types used there
     *
     * @tparam T element type
     * @param gpuResource buffer to read back
     * @param[out] outData output data
     * @return true on success
     * @return false on failure
     */
    template<typename T>
    [[nodiscard]] bool readBack(const Microsoft::WRL::ComPtr<ID3D11Buffer>& gpuResource,
                                std::vector<T>& outData);

    /**
     * @brief Copy a resource on the GPU
     *
     * @param src Source resource
     * @param dest Destination resource
     */
    void copyResource(const Microsoft::WRL::ComPtr<ID3D11Resource>& src,
                      const Microsoft::WRL::ComPtr<ID3D11Resource>& dest);

    /**
     * @brief Generate mips for a shader resource view
     *
     * @param srv Shader resource view
     */
    void generateMips(const Microsoft::WRL::ComPtr<ID3D11ShaderResourceView>& srv);

    /**
     * @brief Flush the device context so released resources are freed
     */
    void flushGPU();

    //
    // Texture helpers.
    //

    /**
     * @brief Load a DDS texture of the load order (loose or archived) through PGGlobals::pgd()
     *
     * @param ddsPath lower case path of the DDS file relative to the data folder
     * @param[out] dds loaded image
     * @return true on success
     * @return false if the file is not in the load order or cannot be loaded
     */
    bool getDDS(const std::filesystem::path& ddsPath,
                DirectX::ScratchImage& dds) const;

    /**
     * @brief Read the header of a DDS texture of the load order. Results are cached, so a texture is read once. A
     * failed read is remembered for the retry interval (setDDSMetadataRetryInterval()), so a burst of lookups does not
     * read a failing file for each of them, and the file is read again afterwards. A file that could not be read this
     * time (a loose file the file system refused to open or read, an archived file whose reader threw
     * BethesdaDirectory::ReadFailure), as opposed to one that is no DDS file or not there, is reported to the run
     * observer by every failed lookup (PGRunObserver::recordTextureReadFailure()).
     *
     * @param ddsPath lower case path of the DDS file relative to the data folder
     * @param[out] ddsMeta the metadata
     * @return true on success
     * @return false if the file is not in the load order or cannot be read
     */
    bool getDDSMetadata(const std::filesystem::path& ddsPath,
                        DirectX::TexMetadata& ddsMeta);

    /**
     * @brief Set how long getDDSMetadata() remembers a failed read before it reads the file again. Five seconds by
     * default.
     *
     * @param interval the time a failure is remembered
     */
    void setDDSMetadataRetryInterval(std::chrono::steady_clock::duration interval);

    /**
     * @brief Pre-populate the DDS metadata cache with known metadata (from a previous run) so the file is not read
     *
     * @param ddsPath path of DDS file (relative to data)
     * @param ddsMeta metadata of the DDS file
     */
    void seedDDSMetadata(const std::filesystem::path& ddsPath,
                         const DirectX::TexMetadata& ddsMeta);

    /**
     * @brief Get a copy of the DDS metadata cache
     *
     * @return std::unordered_map<std::filesystem::path, DirectX::TexMetadata> metadata by DDS path
     */
    [[nodiscard]] std::unordered_map<std::filesystem::path,
                                     DirectX::TexMetadata>
    ddsMetadataCacheSnapshot();

    /**
     * @brief Check whether two textures have the same aspect ratio
     *
     * @param ddsPath1 lower case path of the first DDS file relative to the data folder
     * @param ddsPath2 lower case path of the second DDS file relative to the data folder
     * @return true if both headers could be read and the aspect ratios are equal
     * @return false if they differ or a texture cannot be read (logged as an error)
     */
    bool checkIfAspectRatioMatches(const std::filesystem::path& ddsPath1,
                                   const std::filesystem::path& ddsPath2);

private:
    //
    // Private Helpers.
    //
    static bool isPowerOfTwo(unsigned x);

    /**
     * @brief Whether a DirectXTex result says a file that is there could not be opened or read, as opposed to not
     * being a DDS file or not being there.
     *
     * @param hr the result of a DirectXTex file function
     * @return true if the file system failed on a file that is there; false for a missing file, a file that is no DDS
     * or any other result
     */
    [[nodiscard]] static bool isFileReadError(HRESULT hr);

    /**
     * @brief Remember a failed metadata read for the retry interval, see getDDSMetadata().
     *
     * @param ddsPath lower case path of the DDS file relative to the data folder
     * @param isReadFailure whether the file could not be read this time
     */
    void rememberDDSMetadataFailure(const std::filesystem::path& ddsPath,
                                    bool isReadFailure);

    static DirectX::ScratchImage loadRawPixelsToScratchImage(const std::vector<unsigned char>& rawPixels,
                                                             const size_t& width,
                                                             const size_t& height,
                                                             const size_t& mips,
                                                             DXGI_FORMAT format);
};
